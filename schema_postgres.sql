-- Sooner Buddies tables for Postgres (Supabase). Same tables as schema.sql, in Postgres syntax.
-- The app runs this on startup when DATABASE_URL is set; you can also paste it into the
-- Supabase SQL Editor. Safe to run more than once.
--
-- Everything lives in its own schema, sooner_buddies, so it never collides with other tables in the
-- project (like the static index.html version's tables in "public"). Supabase's public REST API only
-- serves the "public" schema, so the publishable key can't reach these tables at all.
CREATE SCHEMA IF NOT EXISTS sooner_buddies;
SET search_path TO sooner_buddies;

CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    email TEXT NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    gender TEXT NOT NULL,
    major TEXT NOT NULL,
    year TEXT NOT NULL,
    courses TEXT NOT NULL DEFAULT '',
    cc INTEGER NOT NULL DEFAULT 0,
    cc_earned INTEGER NOT NULL DEFAULT 0,
    xp INTEGER NOT NULL DEFAULT 0,
    study_minutes INTEGER NOT NULL DEFAULT 0,
    raids INTEGER NOT NULL DEFAULT 0,
    skin TEXT NOT NULL DEFAULT '#e8b48a',
    outfit TEXT NOT NULL DEFAULT '{}',
    role TEXT NOT NULL DEFAULT 'Student',
    title TEXT NOT NULL DEFAULT '',
    title_kind TEXT NOT NULL DEFAULT '',
    active_pet TEXT NOT NULL DEFAULT '',
    pet_pity INTEGER NOT NULL DEFAULT 0,
    last_seen TEXT NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS raids (
    id BIGINT PRIMARY KEY,                    -- SoonerSports event id, or 1000000000+ for student raids
    sport TEXT NOT NULL,
    sport_slug TEXT NOT NULL DEFAULT '',
    opponent TEXT NOT NULL,
    at_vs TEXT NOT NULL,
    home_away TEXT NOT NULL,
    venue TEXT NOT NULL DEFAULT '',
    city TEXT NOT NULL DEFAULT '',
    starts_at TEXT NOT NULL,
    ends_at TEXT NOT NULL,
    time_text TEXT NOT NULL DEFAULT '',
    tv TEXT NOT NULL DEFAULT '',
    note TEXT NOT NULL DEFAULT '',
    tickets_url TEXT NOT NULL DEFAULT '',
    synced_at TEXT NOT NULL,
    creator_id BIGINT REFERENCES users(id) ON DELETE CASCADE,
    place_key TEXT NOT NULL DEFAULT '',
    boosted_until TEXT NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS user_pets (
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    pet_id TEXT NOT NULL,
    obtained_at TEXT NOT NULL,
    PRIMARY KEY (user_id, pet_id)
);

CREATE TABLE IF NOT EXISTS messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    channel TEXT NOT NULL,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    body TEXT NOT NULL,
    sent_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS messages_by_channel ON messages (channel, id);

CREATE TABLE IF NOT EXISTS inventory (
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    item_id TEXT NOT NULL,
    PRIMARY KEY (user_id, item_id)
);

CREATE TABLE IF NOT EXISTS friendships (
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    friend_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    PRIMARY KEY (user_id, friend_id)
);

CREATE TABLE IF NOT EXISTS parties (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    leader_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    course TEXT NOT NULL,
    dungeon TEXT NOT NULL,
    spot TEXT NOT NULL DEFAULT '',
    description TEXT NOT NULL DEFAULT '',
    capacity INTEGER NOT NULL,
    starts_at TEXT NOT NULL,
    ends_at TEXT NOT NULL,
    raid_id BIGINT REFERENCES raids(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS party_members (
    party_id BIGINT NOT NULL REFERENCES parties(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    joined_at TEXT NOT NULL,
    PRIMARY KEY (party_id, user_id)
);

CREATE TABLE IF NOT EXISTS study_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    dungeon TEXT NOT NULL,
    party_id BIGINT REFERENCES parties(id) ON DELETE SET NULL,
    started_at TEXT NOT NULL,
    ended_at TEXT,
    minutes INTEGER NOT NULL DEFAULT 0,
    cc INTEGER NOT NULL DEFAULT 0,
    xp INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS raid_checkins (
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    raid_id BIGINT NOT NULL REFERENCES raids(id) ON DELETE CASCADE,
    checked_in_at TEXT NOT NULL,
    PRIMARY KEY (user_id, raid_id)
);

CREATE TABLE IF NOT EXISTS clans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    kind TEXT NOT NULL,
    emblem TEXT NOT NULL,
    description TEXT NOT NULL DEFAULT '',
    founder_id BIGINT REFERENCES users(id) ON DELETE SET NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS clans_name_unique ON clans (lower(name));

CREATE TABLE IF NOT EXISTS clan_members (
    clan_id BIGINT NOT NULL REFERENCES clans(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    joined_at TEXT NOT NULL,
    PRIMARY KEY (clan_id, user_id)
);

-- Supabase also exposes tables through its public REST API (the project URL + publishable key).
-- Turning on row-level security with no policies closes that door, so nobody can read password
-- hashes or edit CC with the public key. The Flask server connects as the table owner, so it isn't affected.
ALTER TABLE users ENABLE ROW LEVEL SECURITY;
ALTER TABLE raids ENABLE ROW LEVEL SECURITY;
ALTER TABLE user_pets ENABLE ROW LEVEL SECURITY;
ALTER TABLE messages ENABLE ROW LEVEL SECURITY;
ALTER TABLE inventory ENABLE ROW LEVEL SECURITY;
ALTER TABLE friendships ENABLE ROW LEVEL SECURITY;
ALTER TABLE parties ENABLE ROW LEVEL SECURITY;
ALTER TABLE party_members ENABLE ROW LEVEL SECURITY;
ALTER TABLE study_sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE raid_checkins ENABLE ROW LEVEL SECURITY;
ALTER TABLE clans ENABLE ROW LEVEL SECURITY;
ALTER TABLE clan_members ENABLE ROW LEVEL SECURITY;
